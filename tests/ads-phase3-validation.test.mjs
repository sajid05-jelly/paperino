/** Helper: builds a minimal synthetic MP4 buffer for ISOBMFF box parser testing */
function buildSyntheticMp4({
  durationSeconds = 15,
  timeScale = 1000,
  width = 1280,
  height = 720,
  codec = "avc1",
  totalSizeBytes = 1024,
}) {
  const duration = Math.round(durationSeconds * timeScale);
  const buffer = Buffer.alloc(totalSizeBytes);

  let offset = 0;

  // 1. ftyp box
  const ftypLength = 24;
  buffer.writeUInt32BE(ftypLength, offset);
  buffer.write("ftyp", offset + 4, "ascii");
  buffer.write("isom", offset + 8, "ascii");
  buffer.writeUInt32BE(512, offset + 12);
  buffer.write("mp41", offset + 16, "ascii");
  buffer.write("mp42", offset + 20, "ascii");
  offset += ftypLength;

  // 2. moov box container
  const moovStart = offset;
  buffer.write("moov", offset + 4, "ascii");
  offset += 8;

  // 2a. mvhd box (version 0)
  const mvhdStart = offset;
  const mvhdLength = 108;
  buffer.writeUInt32BE(mvhdLength, offset);
  buffer.write("mvhd", offset + 4, "ascii");
  buffer.writeUInt8(0, offset + 8); // version 0
  buffer.writeUInt32BE(timeScale, offset + 8 + 12); // timeScale at offset 12
  buffer.writeUInt32BE(duration, offset + 8 + 16); // duration at offset 16
  offset += mvhdLength;

  // 2b. trak box
  const trakStart = offset;
  buffer.write("trak", offset + 4, "ascii");
  offset += 8;

  // 2b.i. tkhd box (version 0)
  const tkhdStart = offset;
  const tkhdLength = 92;
  buffer.writeUInt32BE(tkhdLength, offset);
  buffer.write("tkhd", offset + 4, "ascii");
  buffer.writeUInt8(0, offset + 8); // version 0
  // width at 76, height at 80 (16.16 fixed point)
  buffer.writeUInt16BE(width, offset + 8 + 76);
  buffer.writeUInt16BE(height, offset + 8 + 80);
  offset += tkhdLength;

  // 2b.ii. Codec atom string
  const codecLength = 32;
  buffer.writeUInt32BE(codecLength, offset);
  buffer.write("stsd", offset + 4, "ascii");
  buffer.write(codec, offset + 8, "ascii");
  offset += codecLength;

  // Update trak size
  const trakTotalSize = offset - trakStart;
  buffer.writeUInt32BE(trakTotalSize, trakStart);

  // Update moov size
  const moovTotalSize = offset - moovStart;
  buffer.writeUInt32BE(moovTotalSize, moovStart);

  return buffer;
}

describe("Paperino Ads Phase 3 — Production Security, Video Validation & Analytics", () => {
  it("1. Deep MP4 Box Inspection: Validates 720p H.264 video within 30s cap", () => {
    const validVideo = buildSyntheticMp4({
      durationSeconds: 20,
      width: 1280,
      height: 720,
      codec: "avc1",
      totalSizeBytes: 2 * 1024 * 1024, // 2 MB
    });

    const result = inspectMp4VideoProperties(validVideo);
    assert.strictEqual(result.valid, true, "Valid 720p 20s MP4 must pass inspection");
    assert.strictEqual(result.durationSec, 20);
    assert.strictEqual(result.width, 1280);
    assert.strictEqual(result.height, 720);
    assert.ok(result.codec?.includes("H.264"));
  });

  it("2. Deep MP4 Box Inspection: Rejects videos exceeding 30-second duration", () => {
    const longVideo = buildSyntheticMp4({
      durationSeconds: 45, // Exceeds 30s
      width: 1280,
      height: 720,
    });

    const result = inspectMp4VideoProperties(longVideo);
    assert.strictEqual(result.valid, false);
    assert.ok(result.error?.includes("exceeds maximum allowed 30 seconds"));
  });

  it("3. Deep MP4 Box Inspection: Rejects videos exceeding 720p resolution (e.g. 1080p)", () => {
    const highResVideo = buildSyntheticMp4({
      durationSeconds: 15,
      width: 1920,
      height: 1080, // Exceeds 720p
    });

    const result = inspectMp4VideoProperties(highResVideo);
    assert.strictEqual(result.valid, false);
    assert.ok(result.error?.includes("exceeds maximum 720p"));
  });

  it("4. Deep MP4 Box Inspection: Rejects video buffers exceeding 3 MB limit", () => {
    const hugeBuffer = Buffer.alloc(3.5 * 1024 * 1024); // 3.5 MB
    const result = inspectMp4VideoProperties(hugeBuffer);
    assert.strictEqual(result.valid, false);
    assert.ok(result.error?.includes("exceeds 3 MB"));
  });

  it("5. Storage Origin Restriction: Uses exact verified Paperino origin and Cloudflare-generated R2_PUBLIC_URL", () => {
    process.env.R2_ACCOUNT_ID = "testaccount99";
    process.env.R2_BUCKET_NAME = "paperino-ads";
    process.env.R2_PUBLIC_URL = "https://pub-b91c89f2a78d46db98d89cb21884878a.r2.dev";

    // 1. Configured exact R2_PUBLIC_URL generated by Cloudflare
    const r2PublicCheck = validateMediaUrl("https://pub-b91c89f2a78d46db98d89cb21884878a.r2.dev/ads/test.webp", "image");
    assert.strictEqual(r2PublicCheck.valid, true);

    // 2. Specific R2 account S3 direct endpoint
    const r2EndpointCheck = validateMediaUrl(
      "https://paperino-ads.testaccount99.r2.cloudflarestorage.com/ads/video.mp4",
      "video"
    );
    assert.strictEqual(r2EndpointCheck.valid, true);

    // 3. Verified actual existing Paperino production origin
    const paperinoSiteCheck = validateMediaUrl("https://paperino.site/ads/banner.webp", "image");
    assert.strictEqual(paperinoSiteCheck.valid, true);

    const paperinoVercelCheck = validateMediaUrl("https://paperino-eta.vercel.app/ads/banner.webp", "image");
    assert.strictEqual(paperinoVercelCheck.valid, true);

    // 4. Verified Cloudinary Media Storage
    const cloudinaryCheck = validateMediaUrl("https://res.cloudinary.com/ykdgsee2/image/upload/v12345/ad.webp", "image");
    assert.strictEqual(cloudinaryCheck.valid, true);

    const unauthorizedCloudinary = validateMediaUrl("https://res.cloudinary.com/attacker_cloud/image/upload/v12345/ad.webp", "image");
    assert.strictEqual(unauthorizedCloudinary.valid, false);

    // 5. Unrelated third-party R2 account MUST be rejected
    const unrelatedR2 = validateMediaUrl(
      "https://attacker-bucket.unknownaccount.r2.cloudflarestorage.com/ads/test.webp",
      "image"
    );
    assert.strictEqual(unrelatedR2.valid, false);
    assert.ok(unrelatedR2.error?.includes("Unapproved media storage origin"));

    // 6. Arbitrary third party domain MUST be rejected
    const arbitraryUrl = validateMediaUrl("https://unrelated-site.com/malicious.webp", "image");
    assert.strictEqual(arbitraryUrl.valid, false);
  });

  it("6. Analytics Payload Validation: Enforces placement ID, timestamp freshness, and event type", () => {
    const validEvent = {
      campaignId: "camp_123",
      placementId: "home_top",
      event: "impression",
      timestamp: Date.now(),
    };

    const staleEvent = {
      ...validEvent,
      timestamp: Date.now() - 400000, // >5 minutes skew
    };

    const invalidPlacement = {
      ...validEvent,
      placementId: "fake_slot_404",
    };

    assert.strictEqual(typeof validEvent.campaignId, "string");
    assert.ok(validEvent.placementId === "home_top");
    assert.ok(Math.abs(Date.now() - validEvent.timestamp) < 300000, "Timestamp must be within 5 minutes");
    assert.ok(Math.abs(Date.now() - staleEvent.timestamp) > 300000, "Stale timestamp must be flagged");
    assert.notStrictEqual(invalidPlacement.placementId, "home_top");
  });

  it("7. Single Active Video Coordination Lock logic", () => {
    let activePlayingSlotId = null;

    function requestVideoPlay(slotId) {
      if (activePlayingSlotId === null || activePlayingSlotId === slotId) {
        activePlayingSlotId = slotId;
        return true;
      }
      return false;
    }

    function releaseVideoPlay(slotId) {
      if (activePlayingSlotId === slotId) {
        activePlayingSlotId = null;
      }
    }

    // Slot 1 requests play -> granted
    assert.strictEqual(requestVideoPlay("slot_home_featured"), true);
    assert.strictEqual(activePlayingSlotId, "slot_home_featured");

    // Slot 2 requests play while Slot 1 is active -> denied
    assert.strictEqual(requestVideoPlay("slot_pulse_feed"), false);
    assert.strictEqual(activePlayingSlotId, "slot_home_featured");

    // Slot 1 releases lock
    releaseVideoPlay("slot_home_featured");
    assert.strictEqual(activePlayingSlotId, null);

    // Slot 2 now requests play -> granted
    assert.strictEqual(requestVideoPlay("slot_pulse_feed"), true);
    assert.strictEqual(activePlayingSlotId, "slot_pulse_feed");
  });

  it("8. Next Campaign Boundary Timer calculation", () => {
    const now = 1000000;
    const campaigns = [
      { startAt: new Date(now + 45000).toISOString(), expiresAt: new Date(now + 3600000).toISOString() }, // starts in 45s
      { startAt: new Date(now - 60000).toISOString(), expiresAt: new Date(now + 120000).toISOString() }, // expires in 120s
    ];

    let minDelta = Infinity;
    for (const c of campaigns) {
      const s = new Date(c.startAt).getTime();
      const e = new Date(c.expiresAt).getTime();
      if (s > now && s - now < minDelta) minDelta = s - now;
      if (e > now && e - now < minDelta) minDelta = e - now;
    }

    assert.strictEqual(minDelta, 45000, "Next boundary must be exactly the 45-second start transition");
  });
});
